                // Open clicked one
                if (!isOpen) {
                    currentContent.style.maxHeight = currentContent.scrollHeight + 'px';
                    currentContent.classList.remove('opacity-0');

                    currentPlus.classList.add('hidden');
                    currentMinus.classList.remove('hidden');
                }

            });

        });
